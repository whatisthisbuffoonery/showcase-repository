#include "h_pipex.h"

void	unset(int *fd)
{
	if (*fd > 2)
		close(*fd);
	*fd = 0;
}

int	cmd_strchr(char *v)
{
	int	i;

	i = 0;
	while (v[i] && v[i] != ' ')
	{
		if (v[i] == '/')
			return (1);
		i ++;
	}
	return (0);
}
